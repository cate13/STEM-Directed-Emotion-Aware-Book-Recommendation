def reduce_emotion_vector(base_emotion_vector):
    combined = {
        "Joy_Sadness": base_emotion_vector.get("Joy", 0) - base_emotion_vector.get("Sadness", 0),
        "Trust_Disgust": base_emotion_vector.get("Trust", 0) - base_emotion_vector.get("Disgust", 0),
        "Fear_Anger": base_emotion_vector.get("Fear", 0) - base_emotion_vector.get("Anger", 0),
        "Surprise_Anticipation": base_emotion_vector.get("Surprise", 0) - base_emotion_vector.get("Anticipation", 0)
    }
    return combined

def get_correct_correlation_method(emotion_type, topic_type, is_reduced = False):
# Map the combination of parameters to the specific function/variable
    lookup = {
        # (topic_type, emotion_type, is_reduced)
        ("empath", "emotion_intensity", True):  reduced_emotion_intensity_empath,
        ("empath", "emotion", True):           reduced_emotion_empath,
        ("empath", "emotion_intensity", False): emotion_intensity_empath,
        ("empath", "emotion", False):          emotion_empath,
        ("tf_idf", "emotion_intensity", False): emotion_intensity_tf_idf,
        ("tf_idf", "emotion", False):          emotion_tf_idf,
    }

    method = lookup.get((topic_type, emotion_type, is_reduced))

    if method is None:
        raise ValueError(f"Combination {topic_type}/{emotion_type} (reduced={is_reduced}) not supported")
        
    return method

def combine_vectors(emotion_vector, emotion_type, topic_vector, topic_type, is_reduced = False, alpha = 1.0):
    correlation_matrix = get_correct_correlation_method(emotion_type, topic_type, is_reduced)
    
    v_topic = np.array(list(topic_vector.values())) if isinstance(topic_vector, dict) else np.array(topic_vector)

    # 3. Process Emotion Input
    if is_reduced:
        # reduce_emotion_vector returns a dict; extract values
        v_emotion = np.array(list(reduce_emotion_vector(emotion_vector).values()))
    else:
        # Standard emotion dict; extract values
        v_emotion = np.array(list(emotion_vector.values()))


    emotional_adjustment = np.dot(correlation_matrix, v_emotion)

    v_final = v_topic + (emotional_adjustment * alpha)

    return v_final



